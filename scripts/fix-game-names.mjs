#!/usr/bin/env node
/**
 * Correct game names that Steam's search could not match, and link them.
 *
 *   node scripts/fix-game-names.mjs                 # resolve and REPORT only
 *   node scripts/fix-game-names.mjs --out fix.sql   # also emit the SQL
 *
 * Why this exists: `/enrich` only links a game when the match is unambiguous,
 * because a wrong appid means the wrong trailer plays in the rating queue. That
 * conservatism left 26 of the imported games unlinked — but most were not missing
 * from Steam at all, just spelled differently ("Baldurs Gate 3", "Castle Crasher",
 * "TNMT" for TMNT). Fixing the name is enough.
 *
 * It reports every match for eyeballing before anything is applied, and refuses to
 * emit SQL for a name whose top hit does not look like the game asked for.
 */
import { writeFileSync } from 'node:fs';
import { searchStore, getAppDetails } from '../lib/steam.js';

const args = process.argv.slice(2);
const OUT = (() => { const i = args.indexOf('--out'); return i >= 0 ? args[i + 1] : null; })();

/** current name in the library -> the name Steam actually uses */
const FIXES = [
  ['Baldurs Gate 3',                 "Baldur's Gate 3"],
  ['Castle Crasher',                 'Castle Crashers'],
  ["TNMT: Shredder's Revenge",       "Teenage Mutant Ninja Turtles: Shredder's Revenge"],
  ['Trine 4',                        'Trine 4: The Nightmare Prince'],
  ['Trine 5',                        'Trine 5: A Clockwork Conspiracy'],
  ['Tiny Tinas Wonderlands',         "Tiny Tina's Wonderlands"],
  ['Dark Souls 3',                   'DARK SOULS III'],
  ['Dying Light 2',                  'Dying Light 2 Stay Human'],
  ['Dark & Darker',                  'Dark and Darker'],
  ['Torchlight 2',                   'Torchlight II'],
  ['Tetris Effect',                  'Tetris Effect: Connected'],
  ['Cat Quest 3',                    'Cat Quest III'],
  ['Badland GOTY Edition',           'BADLAND: Game of the Year Edition'],
  ['State of Decay 2',               'State of Decay 2: Juggernaut Edition'],
  ['Star Wars: Battlefront 2',       'STAR WARS Battlefront II'],
  ['Age of Empires IV',              'Age of Empires IV: Anniversary Edition'],
  ['Sea of Thieves',                 'Sea of Thieves'],
  ['Supervive',                      'SUPERVIVE'],
  ['Monster Hunter Rise + Sunbreak', 'Monster Hunter Rise'],
];

/**
 * Deliberately NOT attempted, and why. Left unlinked so the library tells the
 * truth rather than pointing at something else:
 *   Valorant        — Riot's own client, never on Steam
 *   Rocket League   — delisted from Steam in 2020, Epic only
 *   Spellbreak      — servers shut down in 2023 and the store page is gone
 *   Overwatch 2     — search returns season packs, not the game
 *   Diablo 4        — Battle.net first; the Steam entry is edition-ambiguous
 *   Farming Simulator — which one? the group did not say
 *   Schach          — German for "chess". Not a game on Steam.
 *   Sea of Thieves: Monkey Island — an expansion, not a separate app
 * These are exactly the cases the manual-add path is for.
 */

const norm = (s) => s.toLowerCase().replace(/[™®©'’:]/g, '').replace(/[^a-z0-9]+/g, ' ').trim();
/** Does the hit plausibly correspond to what we asked for? */
const plausible = (want, got) => {
  const w = norm(want), g = norm(got);
  return g.startsWith(w) || w.startsWith(g) || g.includes(w) || w.includes(g);
};
const sq = (v) => (v == null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);

const ok = [], rejected = [];
for (const [current, corrected] of FIXES) {
  const hits = await searchStore(corrected);
  const top = hits[0];
  if (!top) { rejected.push([current, corrected, 'no Steam result']); }
  else if (!plausible(corrected, top.name)) {
    rejected.push([current, corrected, `top hit "${top.name}" does not match`]);
  } else {
    const meta = await getAppDetails({ // no cache in a script: minimal shim
      prepare: () => ({ bind: () => ({ first: async () => null, run: async () => {} }) }),
    }, top.appid);
    if (!meta) rejected.push([current, corrected, 'no appdetails']);
    else ok.push({ current, meta, appid: top.appid });
  }
  await new Promise((r) => setTimeout(r, 1400));
}

console.log(`\nMATCHED (${ok.length}) — check these before applying:`);
for (const r of ok) {
  console.log(`  ${r.current.padEnd(32)} -> ${r.meta.name} (${r.appid})`
    + `${r.meta.trailer_url ? '  [trailer]' : '  [no trailer]'}`);
}
console.log(`\nNOT APPLIED (${rejected.length}):`);
for (const [c, w, why] of rejected) console.log(`  ${c.padEnd(32)} ${why}`);

if (OUT) {
  const sql = `-- CoopQueue — corrected game names for group 1, with their Steam links.
-- Generated by scripts/fix-game-names.mjs; every match was reviewed before this
-- file was written. Only rows whose name still matches the old spelling are
-- touched, so re-running cannot clobber a later hand-correction.

${ok.map((r) => `UPDATE games SET
    name = ${sq(r.meta.name)}, steam_appid = ${r.appid},
    header_image = ${sq(r.meta.header_image)}, trailer_url = ${sq(r.meta.trailer_url)},
    short_description = ${sq(r.meta.short_description)}, price = ${sq(r.meta.price)},
    release_date = ${sq(r.meta.release_date)}, metacritic = ${r.meta.metacritic ?? 'NULL'},
    genre = COALESCE(genre, ${sq(r.meta.genre)}), enriched_at = unixepoch()
  WHERE group_id = 1 AND name = ${sq(r.current)} AND steam_appid IS NULL;`).join('\n\n')}
`;
  writeFileSync(OUT, sql);
  console.log(`\n-> ${OUT}`);
}
